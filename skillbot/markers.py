"""The marker list (docs/markers.md): for every place the library trains, what to mark in
RuneLite by hand, generated from the library, the color registry and runelite/names.yaml.

`python -m skillbot runelite-profile` already covers NPCs, inventory items, ground items
and marks of grace. What's left are things RuneLite stores by tile:
- Object Markers on objects named in names.yaml: mark them in any color; `runelite-profile
  --from <export>` recolors them by name.
- Ground Markers: label the tile with the registry name; `--from` colors it by its label.
- Everything else (agility obstacles, objects sharing a name like Portal or Altar,
  minigame objects not in names.yaml): mark it and set the color by hand.
"""
from collections import defaultdict

import yaml

from .runelite_profile import NAMES_FILE

AUTO = ("item", "loot", "enemy", "danger")
# Items that stand for whatever you choose, or that the Wiki lookup can't find: tag them in
# game (right-click → Tag) in the registry color.
HAND_ITEMS = ("alch_item", "bones_for_altar", "burnt_fish", "ensouled_head", "quest_item",
              "tithe_fruit", "tithe_seed")


def color_names(spec, registry) -> list[str]:
    """Registry names used anywhere in a method's step (routines included)."""
    found = []

    def walk(v):
        if isinstance(v, str):
            if v in registry.entries and v not in found:
                found.append(v)
        elif isinstance(v, dict):
            for k, x in v.items():
                if k not in ("when_full", "bank_location", "location", "travel"):
                    walk(x)
        elif isinstance(v, (list, tuple)):
            for x in v:
                walk(x)
    walk(spec)
    return found


def classify(name: str, registry, names: dict) -> tuple[str, str]:
    """(how, what): how is auto | object | label | hand."""
    entry = registry.entries[name]
    hexcode = "#{:02X}{:02X}{:02X}".format(*entry.rgb)
    npcs = set(names.get("npcs") or {}) | set(names.get("npc_ids") or {})
    owners = defaultdict(set)
    for color, objs in (names.get("objects") or {}).items():
        for o in objs:
            owners[o.lower()].add(color)
    if name in HAND_ITEMS:
        return "hand", f"Inventory Tag by hand on the item you use: `{name}` {hexcode}"
    if name.startswith("obstacle_"):
        return "hand", (f"Object Marker on obstacle {name.split('_')[1]} of the course, color "
                        f"set by hand: `{name}` {hexcode}")
    if name in npcs:
        return "auto", f"`{name}`: NPC Indicators (in the generated profile)"
    if entry.category in AUTO or name in ("mark_of_grace", "other_player"):
        return "auto", f"`{name}`: in the generated profile"
    if entry.category == "route":
        return "label", f"Ground Marker labelled `{name}` ({hexcode})"
    objs = (names.get("objects") or {}).get(name, [])
    clear = [o for o in objs if len(owners[o.lower()]) == 1]
    if clear:
        return "object", f"Object Marker on {' / '.join(clear)} → `{name}` ({hexcode})"
    shared = f" (shares the name {', '.join(objs)} with another color)" if objs else ""
    return "hand", f"Object Marker, color set by hand: `{name}` {hexcode}{shared}"


def marker_list(methods: dict, registry, names: dict | None = None) -> str:
    names = names if names is not None else yaml.safe_load(NAMES_FILE.read_text())
    by_place = defaultdict(list)
    for m in methods.values():
        by_place[m.location or "anywhere"].append(m)
    out = [
        "# Marker list",
        "",
        "Generated by `python -m skillbot marker-list`; don't edit by hand.",
        "",
        "What to mark in RuneLite (`bot` profile) at each place the library trains, so the",
        "goals planner can use it. Do the places for the methods you'll actually run.",
        "",
        "- **Object Marker → `name`**: mark the object (shift + right-click → Mark object) in",
        "  any color. When a batch is done, export the profile and run",
        "  `python -m skillbot runelite-profile --from <export>`; it recolors them by name.",
        "- **Ground Marker labelled `name`**: mark the tile (shift + right-click → Mark tile),",
        "  then shift + right-click → Label it with the name; `--from` colors it by the label.",
        "- **color set by hand**: shift + right-click the marker → Color, and enter the hex exactly.",
        "- NPCs, inventory items, loot and marks of grace are already in the generated profile.",
        "",
        "After marking a place, stand there and run `python -m skillbot check-setup STEP` (or",
        "`debug`) to confirm the bot sees every highlight.",
        "",
    ]
    respawn = registry.entries.get("respawn")
    if respawn:
        out += ["## everywhere", "",
                "- [ ] Ground Marker labelled `respawn` "
                "(#{:02X}{:02X}{:02X}) on the tile you respawn on".format(*respawn.rgb),
                "- automatic: random events, Genie, graves, other players", ""]
    for place in sorted(by_place, key=lambda p: (p == "anywhere", p)):
        out += [f"## {place}", ""]
        todo, auto, used_by = {}, set(), []
        for m in sorted(by_place[place], key=lambda m: m.name):
            used_by.append(m.name)
            used = color_names(m.step, registry)
            if banks_at(m.step) and "bank_location" not in m.step:
                used.insert(0, "bank")
            for n in used:
                how, what = classify(n, registry, names)
                if how == "auto":
                    auto.add(n)
                else:
                    todo.setdefault((how != "hand", n), what)
        out.append("Used by: " + "; ".join(used_by))
        out.append("")
        locs = sorted({m.step["bank_location"] for m in by_place[place]
                       if "bank_location" in m.step})
        out += [f"- [ ] {what}" for _, what in sorted(todo.items(), key=lambda kv: kv[0])]
        if locs:
            out.append(f"- [ ] `bank` (Object Marker on the booth) at {', '.join(locs)}")
        if not todo and not locs:
            out.append("- nothing to mark by hand")
        if auto:
            out.append(f"- automatic: {', '.join(f'`{n}`' for n in sorted(auto))}")
        out.append("")
    return "\n".join(out)


def banks_at(step: dict) -> bool:
    """Whether the method uses a bank (same rule as `setup`, plus routine bank blocks)."""
    return (step.get("when_full") == "bank" and step.get("task") in ("gather", "combat")) \
        or bool(step.get("withdraw")) or step.get("task") in ("runecraft", "process") \
        or "'bank': True" in str(step.get("routine"))
