"""Generate the RuneLite `bot` profile: highlight colors from the color registry.

RuneLite keeps a profile as a Java properties file (`group.key=value`), and its Profiles
panel can import one. This builds that file:

- Inventory Tags: every registry item, by item id (from the OSRS Wiki's item list)
- NPC Indicators: the names in runelite/names.yaml, each NPC id in its registry color
  (ids from the NPC's OSRS Wiki page), default color `enemy`
- Ground Items: the listed loot in `loot`; Player Indicators: others in `other_player`
- Agility plugin: marks of grace in `mark_of_grace`, its own obstacle boxes off
- With `--from` an exported profile: Object Markers recolored by object name, Ground
  Markers recolored by their label (label a tile `tile_white` and it gets that color).
  Everything else in the export is kept.

Formats follow RuneLite's source: config colors are stored as the signed ARGB integer,
colors inside JSON (tags, markers) as "#AARRGGBB".
"""
import json
import re
from pathlib import Path

import yaml

from .prices import API, USER_AGENT

REPO_DIR = Path(__file__).resolve().parent.parent
NAMES_FILE = REPO_DIR / "runelite" / "names.yaml"
WIKI = "https://oldschool.runescape.wiki/api.php"
PLUGINS = ("npcindicatorsplugin", "objectindicatorsplugin", "groundmarkerplugin",
           "inventorytagsplugin", "grounditemsplugin", "playerindicatorsplugin",
           "agilityplugin")


# ---- Java properties ---------------------------------------------------------------------
def _unescape(s: str) -> str:
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "u" and i + 5 < len(s):
                out.append(chr(int(s[i + 2:i + 6], 16)))
                i += 6
                continue
            out.append({"t": "\t", "n": "\n", "r": "\r", "f": "\f"}.get(n, n))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def read_properties(text: str) -> dict:
    props, pending = {}, ""
    for raw in text.splitlines():
        line = pending + raw.lstrip() if pending else raw.lstrip()
        pending = ""
        if not line or line[0] in "#!":
            continue
        trailing = len(line) - len(line.rstrip("\\"))
        if trailing % 2 == 1:                     # continued on the next line
            pending = line[:-1]
            continue
        m = re.match(r"((?:\\.|[^:=\s\\])*)\s*[:=\s]\s*(.*)$", line)
        key, value = (m.group(1), m.group(2)) if m else (line, "")
        props[_unescape(key)] = _unescape(value)
    return props


def _escape(s: str, key: bool) -> str:
    out = []
    for i, c in enumerate(s):
        if c == "\\":
            out.append("\\\\")
        elif c in "\n\r\t\f":
            out.append({"\n": "\\n", "\r": "\\r", "\t": "\\t", "\f": "\\f"}[c])
        elif key and c in " :=#!":
            out.append("\\" + c)
        elif not key and i == 0 and c == " ":
            out.append("\\ ")
        elif ord(c) > 126:
            out.append(f"\\u{ord(c):04x}")
        else:
            out.append(c)
    return "".join(out)


def write_properties(props: dict) -> str:
    lines = ["#RuneLite profile generated by skillbot (python -m skillbot runelite-profile)"]
    lines += [f"{_escape(k, True)}={_escape(str(v), False)}" for k, v in sorted(props.items())]
    return "\n".join(lines) + "\n"


# ---- colors ------------------------------------------------------------------------------
def argb_int(rgb) -> str:
    """Config value: java.awt.Color#getRGB(), opaque, as a signed int."""
    r, g, b = rgb
    v = (0xFF << 24) | (r << 16) | (g << 8) | b
    return str(v - (1 << 32))


def argb_hex(rgb) -> str:
    """Color inside JSON."""
    return "#FF{:02X}{:02X}{:02X}".format(*rgb)


# ---- ids from the OSRS Wiki --------------------------------------------------------------
def http_json(url: str):
    import urllib.request
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.loads(resp.read())


ID_FIELD = re.compile(r"^\|\s*id\d*\s*=\s*([0-9][0-9,\s]*)", re.MULTILINE)


class WikiIds:
    """Item ids (the prices API's item list) and NPC ids (each NPC's wiki infobox),
    cached in one file so a second run doesn't fetch again."""

    def __init__(self, cache: Path, fetch=http_json):
        self.cache, self.fetch = Path(cache), fetch
        try:
            self.data = json.loads(self.cache.read_text())
        except (OSError, ValueError):
            self.data = {}
        self.data.setdefault("npcs", {})

    def save(self) -> None:
        self.cache.parent.mkdir(parents=True, exist_ok=True)
        self.cache.write_text(json.dumps(self.data))

    def page_ids(self, title: str) -> list[int]:
        """The ids in a Wiki page's infobox (all versions)."""
        from urllib.parse import quote
        url = f"{WIKI}?action=parse&format=json&prop=wikitext&redirects=1&page={quote(title)}"
        try:
            text = self.fetch(url)["parse"]["wikitext"]["*"]
        except (KeyError, TypeError, OSError, ValueError):
            text = ""
        return sorted({int(x) for m in ID_FIELD.findall(text)
                       for x in re.split(r"[,\s]+", m) if x.isdigit()})

    def items(self, name: str) -> list[int]:
        """Tradeable items from the prices API's list; others from their Wiki page."""
        if "items" not in self.data:
            mapping = self.fetch(f"{API}/mapping")
            self.data["items"] = {m["name"].lower(): m["id"] for m in mapping}
        found = self.data["items"].get(name.lower())
        if found is not None:
            return [found]
        pages = self.data.setdefault("item_pages", {})
        if name not in pages:
            pages[name] = self.page_ids(name)
        return pages[name]

    def npc(self, name: str) -> list[int]:
        if name not in self.data["npcs"]:
            self.data["npcs"][name] = self.page_ids(name)
        return self.data["npcs"][name]


# ---- building the profile ----------------------------------------------------------------
def wiki_item_name(tag: str, overrides: dict) -> str:
    if tag in overrides:
        return overrides[tag]
    words = tag.replace("_", " ")
    return words[:1].upper() + words[1:]


def _recolor(points: list, color_for, fmt_like) -> tuple[list, list]:
    """Recolor marker points; returns (points, names not matched)."""
    missed = []
    for p in points:
        rgb = color_for(p)
        if rgb is None:
            missed.append(p.get("name") or p.get("label") or f"tile {p.get('regionX')},"
                          f"{p.get('regionY')} in region {p.get('regionId')}")
            continue
        p["color"] = int(argb_int(rgb)) if isinstance(fmt_like(p), int) else argb_hex(rgb)
    return points, missed


def build(registry, names: dict | None = None, wiki: WikiIds | None = None,
          base: dict | None = None):
    """Returns (properties, report lines)."""
    names = names if names is not None else yaml.safe_load(NAMES_FILE.read_text())
    props = dict(base or {})
    report = []
    entries = registry.entries
    rgb = lambda n: tuple(entries[n].rgb)          # noqa: E731

    for plugin in PLUGINS:
        props[f"runelite.{plugin}"] = "true"

    # Inventory Tags
    tagged, missing = 0, []
    for name, e in entries.items():
        if e.category != "item":
            continue
        item_ids = wiki.items(wiki_item_name(name, names.get("items") or {}))
        if not item_ids:
            missing.append(name)
            continue
        for item_id in item_ids:
            props[f"inventorytags.tag_{item_id}"] = json.dumps({"color": argb_hex(e.rgb)})
        tagged += 1
    report.append(f"Inventory Tags: {tagged} items tagged")
    if missing:
        report.append("  no item of that name on the Wiki (yours to pick: tag it in game, "
                      "right-click → Tag): "
                      + ", ".join(sorted(missing)))

    # NPC Indicators
    highlight = [n.strip() for n in props.get("npcindicators.npcToHighlight", "").split(",")
                 if n.strip()]
    no_ids = []
    fixed_ids = names.get("npc_ids") or {}
    for color, ids in fixed_ids.items():
        for i in ids:
            props[f"npcindicators.highlightcolor_{i}"] = argb_int(rgb(color))
    for color, npc_names in (names.get("npcs") or {}).items():
        if color not in entries:
            report.append(f"  names.yaml: unknown color {color!r}")
            continue
        for npc in npc_names:
            ids = [] if color in fixed_ids else wiki.npc(npc)
            if not ids and color not in fixed_ids and color != "enemy":
                no_ids.append(npc)      # would show in `enemy`: the bot would attack it
                continue
            if npc not in highlight:
                highlight.append(npc)
            for i in ids:
                props[f"npcindicators.highlightcolor_{i}"] = argb_int(rgb(color))
    props["npcindicators.npcToHighlight"] = ", ".join(highlight)
    if "enemy" in entries:
        props["npcindicators.npcColor"] = argb_int(rgb("enemy"))
    report.append(f"NPC Indicators: {len(highlight)} names")
    if no_ids:
        report.append("  left out, no ids found on the Wiki (fix the name in "
                      "runelite/names.yaml, or add the NPC by hand with its color): "
                      + ", ".join(no_ids))

    # Ground Items, Player Indicators, Agility
    if "loot" in entries and names.get("ground_items"):
        props["grounditems.highlightedItems"] = ", ".join(names["ground_items"])
        props["grounditems.highlightedColor"] = argb_int(rgb("loot"))
        props["grounditems.highlightTiles"] = "true"
        report.append(f"Ground Items: {len(names['ground_items'])} items, tiles highlighted")
    if "other_player" in entries:
        props["playerindicators.highlightOthers"] = "true"
        props["playerindicators.nonClanMemberColor"] = argb_int(rgb("other_player"))
    if "mark_of_grace" in entries:
        props["agility.highlightMarks"] = "true"
        props["agility.markHighlight"] = argb_int(rgb("mark_of_grace"))
        props["agility.showClickboxes"] = "false"

    # Object Markers and Ground Markers, from an export
    if base is not None:
        owners = {}
        for color, objs in (names.get("objects") or {}).items():
            for o in objs:
                owners.setdefault(o.lower(), set()).add(color)
        ambiguous = sorted({o for o, c in owners.items() if len(c) > 1})

        def object_color(p):
            c = owners.get(str(p.get("name", "")).lower())
            return rgb(next(iter(c))) if c and len(c) == 1 and next(iter(c)) in entries else None

        def label_color(p):
            label = str(p.get("label") or "").strip().lower().replace(" ", "_")
            return rgb(label) if label in entries else None

        done = {"objectindicators.region_": 0, "groundMarker.region_": 0}
        missed_all = {k: [] for k in done}
        for key in list(props):
            for prefix, color_for in (("objectindicators.region_", object_color),
                                      ("groundMarker.region_", label_color)):
                if key.startswith(prefix):
                    try:
                        points = json.loads(props[key])
                    except ValueError:
                        continue
                    before = len(points)
                    points, missed = _recolor(points, color_for, lambda p: p.get("color"))
                    props[key] = json.dumps(points, separators=(",", ":"))
                    done[prefix] += before - len(missed)
                    missed_all[prefix] += missed
        report.append(f"Object Markers: {done['objectindicators.region_']} recolored")
        if missed_all["objectindicators.region_"]:
            report.append("  left as they were (not in names.yaml, or a name used for two "
                          "colors: " + ", ".join(ambiguous) + "): "
                          + ", ".join(sorted(set(missed_all["objectindicators.region_"]))))
        report.append(f"Ground Markers: {done['groundMarker.region_']} recolored by label")
        if missed_all["groundMarker.region_"]:
            report.append("  without a registry name as label: "
                          + ", ".join(sorted(set(missed_all["groundMarker.region_"]))[:20]))
    else:
        report.append("Object Markers / Ground Markers: not included (mark them in game, export "
                      "the profile, then run again with --from; see docs/runelite-profile.md)")
    return props, report
